#!/usr/bin/env python3
"""Export the five ISO 19650 extraction files to one self-contained Cypher script.

Output: tmp/load_iso19650_kg.cypher - paste into Neo4j Browser, Aura, or pipe
through cypher-shell. No APOC, no import-directory config, no driver needed.

Flattening decisions (Neo4j cannot store nested maps as properties):
  provenance {standard, clause}      -> provenance_standard, provenance_clause
  definition_provenance (4 nodes)    -> definition_provenance_standard/_clause
Everything else in the files is already a primitive or a list of primitives.

Node key: id (unique constraint). Neo4j label = the node's `label` field plus
a shared :Iso19650 label; `part` records the source file. Relationships MERGE
on type + provenance, so the deliberate cross-file duplicate assertions (same
triple, two standards) load as two edges, each with its own provenance.
"""
import json, os
os.chdir(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

FILES = {
    "data/iso19650-1_extraction_v4.json": "ISO 19650-1",
    "data/iso19650-2_extraction_v1.json": "ISO 19650-2",
    "data/iso19650-3_extraction_v1.2.json": "ISO 19650-3",
    "data/iso19650-4_extraction_v1.json": "ISO 19650-4",
    "data/iso19650-5_extraction_v1.json": "ISO 19650-5",
    "data/iso19650-6_extraction_v2.json": "ISO 19650-6",
}
OUT = "data/generated/load_iso19650_kg.cypher"


def lit(v):
    """Python value -> Cypher literal. json.dumps is valid Cypher for ASCII
    strings, numbers, booleans and flat lists (same escape rules)."""
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return json.dumps(v)
    if isinstance(v, list):
        assert all(isinstance(x, (str, int, float, bool)) for x in v), f"nested list: {v}"
        return "[" + ", ".join(lit(x) for x in v) + "]"
    raise TypeError(f"unsupported property type {type(v)}: {v!r}")


# sanity check on the escaper itself
assert lit('he said "a\\b"\nx') == '"he said \\"a\\\\b\\"\\nx"'

lines = [
    "// ISO 19650 series -> Neo4j knowledge graph (ontology / concept layer)",
    "// Generated by backend/graphdb/export_neo4j.py - do not edit by hand, regenerate instead.",
    "CREATE CONSTRAINT iso19650_id IF NOT EXISTS FOR (n:Iso19650) REQUIRE n.id IS UNIQUE;",
]

seen_ids = set()
n_nodes = n_rels = 0
for f, part in FILES.items():
    d = json.load(open(f))
    lines.append(f"\n// ---- {part} nodes ({f}) ----")
    for n in d["nodes"]:
        assert n["id"] not in seen_ids, f"duplicate id across files: {n['id']}"
        seen_ids.add(n["id"])
        props = {"part": part}
        for k, v in n.items():
            if k == "label":
                continue
            elif k == "provenance":
                props["provenance_standard"] = v["standard"]
                props["provenance_clause"] = v["clause"]
            elif k == "definition_provenance":
                props["definition_provenance_standard"] = v["standard"]
                props["definition_provenance_clause"] = v["clause"]
            else:
                props[k] = v
        body = ", ".join(f"{k}: {lit(v)}" for k, v in sorted(props.items()))
        lines.append(f"MERGE (n:Iso19650 {{id: {lit(n['id'])}}}) SET n:{n['label']}, n += {{{body}}};")
        n_nodes += 1

for f, part in FILES.items():
    d = json.load(open(f))
    lines.append(f"\n// ---- {part} relationships ({f}) ----")
    for r in d["relationships"]:
        assert r["from"] in seen_ids and r["to"] in seen_ids, f"dangling: {r}"
        props = {"provenance_standard": r["provenance"]["standard"],
                 "provenance_clause": r["provenance"]["clause"]}
        merge_body = ", ".join(f"{k}: {lit(v)}" for k, v in sorted(props.items()))
        set_note = f" SET r.note = {lit(r['note'])}" if r.get("note") else ""
        lines.append(
            f"MATCH (a:Iso19650 {{id: {lit(r['from'])}}}), (b:Iso19650 {{id: {lit(r['to'])}}}) "
            f"MERGE (a)-[r:{r['type']} {{{merge_body}}}]->(b){set_note};")
        n_rels += 1

open(OUT, "w").write("\n".join(lines) + "\n")

# self-check: statement count and pure ASCII
text = open(OUT).read()
assert all(ord(c) < 128 for c in text), "non-ASCII leaked into Cypher"
stmts = text.count(";\n") + text.rstrip().endswith(";")
print(f"wrote {OUT}: {n_nodes} node statements + {n_rels} relationship statements "
      f"(+1 constraint), {len(text)//1024} KiB")
